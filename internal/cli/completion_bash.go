package cli

import (
	"fmt"
	"io"
	"strings"
)

// writeBashCompletion writes the bash completion script, generated from the
// command table. It needs no bash-completion package and runs on bash 3.2.
func writeBashCompletion(w io.Writer) {
	var b strings.Builder
	b.WriteString(`# bash completion for heavyq. Generated by "heavyq completion bash"; do not edit.
#   source <(heavyq completion bash)

# Candidates one per line (file names may hold spaces).
_heavyq_lines() {
    local IFS=$'\n'
    COMPREPLY=($(compgen "$@"))
}

_heavyq() {
    local cur prev cmd sub i w words flags
    COMPREPLY=()
    cur="${COMP_WORDS[COMP_CWORD]}"
    prev=""
    if [ "$COMP_CWORD" -gt 0 ]; then prev="${COMP_WORDS[COMP_CWORD-1]}"; fi
    cmd=""; sub=""; i=1
    # Find the command and its subcommand, skipping flags and the values of flags that take one.
    while [ "$i" -lt "$COMP_CWORD" ]; do
        w="${COMP_WORDS[$i]}"
        case "$w" in
            --)
                # After "--" comes the user's own command: complete a program name, then its files.
                if [ "$COMP_CWORD" -eq $((i + 1)) ]; then
                    _heavyq_lines -c -- "$cur"
                else
                    _heavyq_lines -f -- "$cur"
                fi
                return 0 ;;
`)
	b.WriteString("            " + strings.Join(valueFlagWords(), "|") + ") i=$((i + 2)); continue ;;\n")
	b.WriteString(`            -*) ;;
            *) if [ -z "$cmd" ]; then cmd="$w"; elif [ -z "$sub" ]; then sub="$w"; fi ;;
        esac
        i=$((i + 1))
    done
    # What may complete the value of a flag.
    case "$prev" in
`)
	for _, v := range valueFlags() {
		var action string
		switch {
		case len(v.Choices) > 0:
			action = fmt.Sprintf(`COMPREPLY=($(compgen -W "%s" -- "$cur"))`, strings.Join(v.Choices, " "))
		case v.Path == "file":
			action = `_heavyq_lines -f -- "$cur"`
		case v.Path == "dir":
			action = `_heavyq_lines -d -- "$cur"`
		default:
			action = ":" // a free-form value: offer nothing
		}
		fmt.Fprintf(&b, "        %s) %s; return 0 ;;\n", v.Word, action)
	}
	b.WriteString(`    esac
    case "$cmd" in [1-9]) cmd=run ;; esac
    case "$cmd:$sub" in
`)
	for _, r := range completionRows() {
		plain, flags := splitWords(r.Words)
		fmt.Fprintf(&b, "        \"%s\") words=\"%s\"; flags=\"%s\" ;;\n", rowPattern(r), strings.Join(plain, " "), strings.Join(flags, " "))
	}
	b.WriteString(`        *) words=""; flags="" ;;
    esac
    # Flags only once a dash is typed (or when there is nothing else to offer).
    if [ -z "$words" ] || [ "${cur#-}" != "$cur" ]; then words="$flags"; fi
    COMPREPLY=($(compgen -W "$words" -- "$cur"))
}
complete -F _heavyq heavyq
`)
	_, _ = io.WriteString(w, b.String())
}

// rowPattern is the "cmd:sub" case pattern of a row ("*" matches anything).
func rowPattern(r compRow) string { return r.Cmd + ":" + r.Sub }

// splitWords separates plain words from flags.
func splitWords(words []compWord) (plain, flags []string) {
	for _, w := range words {
		if strings.HasPrefix(w.Text, "-") {
			flags = append(flags, w.Text)
		} else {
			plain = append(plain, w.Text)
		}
	}
	return plain, flags
}

// valueFlagWords are the spellings of every flag that takes a value.
func valueFlagWords() []string {
	var out []string
	for _, v := range valueFlags() {
		out = append(out, v.Word)
	}
	return out
}
