package cli

import (
	"fmt"
	"io"
	"strings"
)

// fishQuote single-quotes s for fish (only \ and ' need escaping inside).
func fishQuote(s string) string {
	s = strings.ReplaceAll(s, `\`, `\\`)
	return "'" + strings.ReplaceAll(s, "'", `\'`) + "'"
}

// fishQuotedWords renders words as space-separated single-quoted fish words.
func fishQuotedWords(words []string) string {
	q := make([]string, len(words))
	for i, w := range words {
		q[i] = fishQuote(w)
	}
	return strings.Join(q, " ")
}

// fishFlag renders `complete` options for one flag under condition cond.
func fishFlag(b *strings.Builder, cond string, f flagSpec) {
	fmt.Fprintf(b, "complete -c heavyq -n %s", fishQuote(cond))
	if f.Short != "" {
		fmt.Fprintf(b, " -s %s", f.Short)
	}
	if f.Long != "" {
		fmt.Fprintf(b, " -l %s", f.Long)
	}
	switch {
	case len(f.Choices) > 0:
		fmt.Fprintf(b, " -x -a %s", fishQuote(strings.Join(f.Choices, " ")))
	case f.Path != "":
		b.WriteString(" -r -F")
	case f.Value != "":
		b.WriteString(" -x")
	}
	fmt.Fprintf(b, " -d %s\n", fishQuote(f.Help))
}

// writeFishCompletion writes the fish completion script, generated from the
// command table. Save it as ~/.config/fish/completions/heavyq.fish.
func writeFishCompletion(w io.Writer) {
	var b strings.Builder
	b.WriteString(`# fish completion for heavyq. Generated by "heavyq completion fish"; do not edit.
#   heavyq completion fish > ~/.config/fish/completions/heavyq.fish

# The words typed so far that are neither flags nor values of flags: command, then subcommand.
# A priority 1-9 counts as "run". Stops at "--" (what follows is the user's own command).
function __heavyq_positionals
    set -l t (commandline -opc)
    set -e t[1]
    set -l skip 0
    set -l out
    for w in $t
        if test $skip = 1
            set skip 0
            continue
        end
        if test "$w" = '--'
            break
        end
        switch $w
            case ` + fishQuotedWords(valueFlagWords()) + `
                set skip 1
            case '-*'
            case '*'
                set -a out $w
        end
    end
    if string match -qr '^[1-9]$' -- "$out[1]"
        set out[1] run
    end
    printf '%s\n' $out
end

# __heavyq_at CMD [SUB]: is the line at that command (and subcommand; "" means none yet)?
function __heavyq_at
    set -l p (__heavyq_positionals)
    test "$p[1]" = "$argv[1]"; or return 1
    set -q argv[2]; or return 0
    test "$p[2]" = "$argv[2]"
end

complete -c heavyq -f
`)
	fishFlag(&b, "true", configFlag)
	b.WriteString("complete -c heavyq -n 'true' -s h -l help -d 'show the usage'\n")
	b.WriteString("complete -c heavyq -n '__heavyq_at \"\"' -l version -d 'print the version'\n")
	for _, r := range completionRows() {
		cond := fmt.Sprintf("__heavyq_at \"%s\"", r.Cmd)
		if r.Sub != "*" {
			cond += fmt.Sprintf(" \"%s\"", r.Sub)
		}
		for _, cw := range r.Words {
			if strings.HasPrefix(cw.Text, "-") {
				continue // flags are declared below, with their value handling
			}
			fmt.Fprintf(&b, "complete -c heavyq -n %s -a %s", fishQuote(cond), fishQuote(cw.Text))
			if cw.Desc != "" {
				fmt.Fprintf(&b, " -d %s", fishQuote(cw.Desc))
			}
			b.WriteString("\n")
		}
	}
	for _, c := range commandTable {
		for _, f := range c.Flags {
			fishFlag(&b, fmt.Sprintf("__heavyq_at \"%s\"", c.Name), f)
		}
		for _, s := range c.Subs {
			for _, f := range s.Flags {
				fishFlag(&b, fmt.Sprintf("__heavyq_at \"%s\" \"%s\"", c.Name, s.Name), f)
			}
		}
	}
	_, _ = io.WriteString(w, b.String())
}
