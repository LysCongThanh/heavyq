package cli

import (
	"fmt"
	"io"
	"strings"
)

// zshQuote renders one _describe entry "word:description" as a single-quoted
// zsh word (colons in the word would need a backslash; none has one).
func zshQuote(w compWord) string {
	text := w.Text
	if w.Desc != "" {
		text += ":" + w.Desc
	}
	return "'" + strings.ReplaceAll(text, "'", `'\''`) + "'"
}

func zshList(words []compWord) string {
	parts := make([]string, 0, len(words))
	for _, w := range words {
		parts = append(parts, zshQuote(w))
	}
	return strings.Join(parts, " ")
}

// writeZshCompletion writes the zsh completion script, generated from the
// command table. Save it as _heavyq in a directory on $fpath.
func writeZshCompletion(w io.Writer) {
	var b strings.Builder
	b.WriteString(`#compdef heavyq
# zsh completion for heavyq. Generated by "heavyq completion zsh"; do not edit.
#   heavyq completion zsh > "${fpath[1]}/_heavyq"
_heavyq() {
    local cur prev cmd sub i w
    local -a plain flags
    cur="${words[CURRENT]}"
    prev="${words[CURRENT-1]}"
    cmd=""; sub=""; i=2
    # Find the command and its subcommand, skipping flags and the values of flags that take one.
    while (( i < CURRENT )); do
        w="${words[i]}"
        case "$w" in
            --)
                # After "--" comes the user's own command: complete a program name, then its files.
                if (( CURRENT == i + 1 )); then _command_names -e; else _files; fi
                return ;;
`)
	b.WriteString("            " + strings.Join(valueFlagWords(), "|") + ") (( i += 2 )); continue ;;\n")
	b.WriteString(`            -*) ;;
            *) if [[ -z $cmd ]]; then cmd=$w; elif [[ -z $sub ]]; then sub=$w; fi ;;
        esac
        (( i += 1 ))
    done
    # What may complete the value of a flag.
    case "$prev" in
`)
	for _, v := range valueFlags() {
		var action string
		switch {
		case len(v.Choices) > 0:
			action = "compadd -- " + strings.Join(v.Choices, " ")
		case v.Path == "file":
			action = "_files"
		case v.Path == "dir":
			action = "_files -/"
		default:
			action = ":" // a free-form value: offer nothing
		}
		fmt.Fprintf(&b, "        %s) %s; return ;;\n", v.Word, action)
	}
	b.WriteString(`    esac
    [[ $cmd == [1-9] ]] && cmd=run
    case "$cmd:$sub" in
`)
	for _, r := range completionRows() {
		var plain, flags []compWord
		for _, cw := range r.Words {
			if strings.HasPrefix(cw.Text, "-") {
				flags = append(flags, cw)
			} else {
				plain = append(plain, cw)
			}
		}
		fmt.Fprintf(&b, "        %s) plain=(%s); flags=(%s) ;;\n", rowPattern(r), zshList(plain), zshList(flags))
	}
	b.WriteString(`        *) plain=(); flags=() ;;
    esac
    # Flags only once a dash is typed (or when there is nothing else to offer).
    if (( ${#plain} )) && [[ $cur != -* ]]; then
        _describe -t commands 'heavyq' plain
    else
        _describe -t options 'option' flags
    fi
}
if [ "$funcstack[1]" = "_heavyq" ]; then
    _heavyq "$@"
else
    compdef _heavyq heavyq
fi
`)
	_, _ = io.WriteString(w, b.String())
}
